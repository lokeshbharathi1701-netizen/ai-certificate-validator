/* ResultCard.jsx — Full verdict display with confidence gauge, download, and copy */
import { useEffect, useState, useCallback } from 'react';
import BoxOverlay        from './BoxOverlay';
import OcrPanel          from './OcrPanel';
import VerificationPanel from './VerificationPanel';

/** SVG circular confidence gauge */
function ConfidenceRing({ value, isFake }) {
  const r  = 42;
  const cx = 56;
  const cy = 56;
  const circumference = 2 * Math.PI * r;
  const [dashOffset, setDashOffset] = useState(circumference);
  const color = isFake ? '#ef4444' : '#10b981';

  useEffect(() => {
    const t = setTimeout(() => {
      setDashOffset(circumference * (1 - value / 100));
    }, 150);
    return () => clearTimeout(t);
  }, [value, circumference]);

  return (
    <svg viewBox="0 0 112 112" className="confidence-ring-svg" aria-hidden="true">
      {/* Track */}
      <circle cx={cx} cy={cy} r={r} fill="none" stroke="rgba(255,255,255,0.08)" strokeWidth="8" />
      {/* Fill */}
      <circle
        cx={cx} cy={cy} r={r}
        fill="none"
        stroke={color}
        strokeWidth="8"
        strokeLinecap="round"
        strokeDasharray={circumference}
        strokeDashoffset={dashOffset}
        style={{ transition: 'stroke-dashoffset 1.2s cubic-bezier(0.4,0,0.2,1)', transformOrigin: 'center', transform: 'rotate(-90deg)' }}
      />
      {/* Label */}
      <text x={cx} y={cy - 6}  textAnchor="middle" fill={color} fontSize="18" fontWeight="800">{value}%</text>
      <text x={cx} y={cy + 12} textAnchor="middle" fill="rgba(255,255,255,0.45)" fontSize="8" fontWeight="600" letterSpacing="1">CONFIDENCE</text>
    </svg>
  );
}

export default function ResultCard({ result, imageFile, onReset }) {
  const isFake     = result.prediction === 'Fake';
  const confidence = result.confidence ?? 0;
  const boxes      = result.boxes ?? [];
  const imageUrl   = result.preview_image || (
    imageFile && !imageFile.name?.toLowerCase().endsWith('.pdf') && imageFile.type !== 'application/pdf'
      ? URL.createObjectURL(imageFile)
      : null
  );
  const [copied, setCopied]       = useState(false);
  const [showRaw, setShowRaw]     = useState(false);
  const [isZoomed, setIsZoomed]   = useState(false);

  // ── Download Report ──────────────────────────────────────────
  const handleDownload = useCallback(() => {
    const ocr    = result.ocr   ?? {};
    const verify = result.verification ?? {};
    const lines = [
      '═══════════════════════════════════════════',
      '     CertVerify AI — Analysis Report',
      '═══════════════════════════════════════════',
      '',
      `File        : ${result.filename ?? imageFile?.name ?? 'Unknown'}`,
      `Analysed At : ${result.timestamp ? new Date(result.timestamp).toLocaleString() : new Date().toLocaleString()}`,
      `Cert Type   : ${verify.cert_type_label ?? 'General'}`,
      `Model       : ${result.model_used ?? 'N/A'}`,
      `Processing  : ${result.processing_time_ms ? result.processing_time_ms + 'ms' : 'N/A'}`,
      '',
      '── AI Authenticity Verdict ──────────────────',
      `Prediction  : ${result.prediction}`,
      `Confidence  : ${confidence}%`,
      `Regions     : ${boxes.length} suspicious region(s) flagged`,
      '',
      '── Type-Specific Verification ───────────────',
      `Auth. Score : ${verify.authenticity_score ?? 'N/A'}%`,
      `Is Verified : ${verify.is_verified ? 'Yes' : 'No'}`,
      verify.verdict_reason ? `Verdict     : ${verify.verdict_reason}` : '',
      '',
      ...(verify.checks ?? []).map(c =>
        `  [${c.status.toUpperCase().padEnd(4)}] ${c.label}: ${c.detail}`
      ),
      '',
      '── Extracted Information ────────────────────',
      `Student     : ${ocr.student     ?? 'N/A'}`,
      `Cert Number : ${ocr.certificate_number ?? 'N/A'}`,
      `Institution : ${ocr.institute   ?? 'N/A'}`,
      `Issue Date  : ${ocr.date        ?? 'N/A'}`,
      `Course      : ${ocr.course      ?? 'N/A'}`,
      '',
      '── Summary ──────────────────────────────────',
      result.summary ?? '',
      '',
      '═══════════════════════════════════════════',
      'Generated by CertVerify AI · Ideathon 2026',
      '═══════════════════════════════════════════',
    ];
    const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement('a');
    a.href     = url;
    a.download = `certverify_report_${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }, [result, imageFile, confidence, boxes]);

  // ── Copy Summary ─────────────────────────────────────────────
  const handleCopy = useCallback(() => {
    navigator.clipboard.writeText(result.summary ?? '').then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  }, [result.summary]);

  return (
    <div className="result-section" id="result-section">

      {/* ── Verdict Banner ─────────────────────────────────────── */}
      <div className={`verdict-banner ${isFake ? 'fake' : 'genuine'}`} id="verdict-banner">
        <div className="verdict-left">
          <ConfidenceRing value={confidence} isFake={isFake} />
          <div>
            <p className="verdict-label">AI Verdict</p>
            <p className="verdict-text" id="verdict-text">
              {isFake ? '⚠ FAKE' : '✅ GENUINE'}
            </p>
            {result.model_used && (
              <span className="model-chip">🤖 {result.model_used}</span>
            )}
            {result.processing_time_ms && (
              <span className="model-chip" style={{ marginLeft: 6 }}>
                ⏱ {result.processing_time_ms}ms
              </span>
            )}
          </div>
        </div>

        <div className="verdict-actions">
          <button
            className="action-btn download-btn"
            onClick={handleDownload}
            id="download-report-btn"
            title="Download analysis report as text file"
          >
            ⬇ Download Report
          </button>
        </div>
      </div>

      {/* ── Image + OCR Grid ──────────────────────────────────── */}
      <div className="results-grid">
        {/* Certificate image with bounding boxes */}
        <div className="glass image-panel" id="image-panel">
          <p className="panel-title">
            <span className="panel-title-dot" />
            Certificate Image
            {boxes.length > 0 && (
              <span className="region-badge">
                ⚠ {boxes.length} region{boxes.length !== 1 ? 's' : ''} flagged
              </span>
            )}
          </p>
          {imageUrl ? (
            <>
              <BoxOverlay imageSrc={imageUrl} boxes={boxes} isFake={isFake} />
              <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: 8 }}>
                <button
                  type="button"
                  className="ghost-btn small-btn"
                  onClick={() => setIsZoomed(true)}
                  style={{ fontSize: '0.78rem', padding: '4px 10px', gap: 4 }}
                >
                  🔍 View Full Size
                </button>
              </div>
            </>
          ) : (
            <p style={{ color: 'var(--text-muted)', fontSize: '0.85rem' }}>
              Image preview unavailable
            </p>
          )}
          {boxes.length === 0 && !isFake && (
            <p className="region-count">✅ No suspicious regions detected</p>
          )}
        </div>

        {/* OCR extracted fields */}
        <OcrPanel ocr={result.ocr ?? {}} />
      </div>

      {/* ── Type-specific Government Verification ─────────── */}
      {result.verification && (
        <VerificationPanel verification={result.verification} />
      )}

      {/* ── Summary ───────────────────────────────────────────── */}
      {result.summary && (
        <div className="glass summary-card" id="summary-card">
          <div className="summary-header">
            <p className="panel-title" style={{ marginBottom: 0 }}>
              <span className="panel-title-dot" style={{ background: 'var(--yellow)' }} />
              Analysis Summary
            </p>
            <button
              className="copy-btn"
              onClick={handleCopy}
              id="copy-summary-btn"
              title="Copy summary to clipboard"
            >
              {copied ? '✓ Copied!' : '📋 Copy'}
            </button>
          </div>
          <p className="summary-text">{result.summary}</p>
        </div>
      )}

      {/* ── Raw OCR Text (expandable) ──────────────────────────── */}
      {result.ocr?.raw_text?.length > 0 && (
        <div className="glass raw-text-card" id="raw-text-card">
          <button
            className="raw-text-toggle"
            onClick={() => setShowRaw(r => !r)}
            id="raw-text-toggle"
          >
            <span className="panel-title-dot" style={{ background: 'var(--purple)' }} />
            Raw OCR Text ({result.ocr.raw_text.length} lines)
            <span className="toggle-arrow">{showRaw ? '▲' : '▼'}</span>
          </button>
          {showRaw && (
            <div className="raw-text-content">
              {result.ocr.raw_text.map((line, i) => (
                <span key={i} className="raw-text-line">{line}</span>
              ))}
            </div>
          )}
        </div>
      )}

      {/* ── Reset ─────────────────────────────────────────────── */}
      <div style={{ textAlign: 'center', marginTop: 24 }}>
        <button id="reset-btn" className="reset-btn" onClick={onReset}>
          🔄 Analyse Another Certificate
        </button>
      </div>

      {/* ── Lightbox Full-Size Modal ──────────────────────────── */}
      {isZoomed && imageUrl && (
        <div
          className="cert-lightbox-modal"
          onClick={() => setIsZoomed(false)}
          style={{
            position: 'fixed',
            inset: 0,
            background: 'rgba(0, 0, 0, 0.88)',
            backdropFilter: 'blur(8px)',
            zIndex: 9999,
            display: 'flex',
            flexDirection: 'column',
            alignItems: 'center',
            justifyContent: 'center',
            padding: 24,
            cursor: 'zoom-out',
          }}
        >
          <div
            style={{
              position: 'relative',
              maxWidth: '92vw',
              maxHeight: '92vh',
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'center',
            }}
            onClick={(e) => e.stopPropagation()}
          >
            <div style={{ width: '100%', display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 12 }}>
              <span style={{ color: 'var(--text-secondary)', fontSize: '0.88rem', fontWeight: 600 }}>
                {result.filename || 'Certificate Preview'} · Full Resolution View
              </span>
              <button
                type="button"
                onClick={() => setIsZoomed(false)}
                className="ghost-btn small-btn"
                style={{ color: '#fff', fontSize: '0.88rem', padding: '4px 12px' }}
              >
                ✕ Close
              </button>
            </div>
            <img
              src={imageUrl}
              alt="Full resolution certificate"
              style={{
                maxWidth: '90vw',
                maxHeight: '82vh',
                borderRadius: 12,
                boxShadow: '0 25px 60px rgba(0,0,0,0.9)',
                border: '1px solid var(--border)',
                objectFit: 'contain',
                background: '#000',
              }}
            />
          </div>
        </div>
      )}
    </div>
  );
}
